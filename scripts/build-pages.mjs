import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const appearanceSource = (await readFile(new URL('api/pages/appearance.js', root), 'utf8')).replace(/\r\n?/g, '\n');
const appearanceExports = 'module.exports = { normalizeHex, resolveAppearance, appearanceIssues, typographyMetrics };';
if (appearanceSource.split(appearanceExports).length !== 2) throw new Error('Appearance source must have one canonical CommonJS export');
const browserAppearance = '/* Generated from api/pages/appearance.js by npm run build:pages. Do not edit. */\n'
  + appearanceSource.replace(appearanceExports, 'export { normalizeHex, resolveAppearance, appearanceIssues, typographyMetrics };');
async function output(filename, contents) {
  const url = new URL(filename, root);
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8').catch(() => '') !== contents) throw new Error(`${filename} is stale; run npm run build:pages`);
  } else await writeFile(url, contents);
}
// Generate/check before bundling: model.js imports appearance even on a clean
// checkout. --check must never repair a missing/stale module as a side effect.
await output('public/pages/appearance.js', browserAppearance);
const result = await build({ absWorkingDir: fileURLToPath(root), entryPoints: ['public/pages/editor-source.js'],
  bundle: true, format: 'esm', platform: 'browser', target: ['es2020'], minify: true, legalComments: 'inline', write: false,
  banner: { js: '/* Generated by npm run build:pages. Pinned sources and MIT notices: ./vendor/LICENSES.txt */' } });
const packages = ['sortablejs','orderedmap','prosemirror-commands','prosemirror-history','prosemirror-keymap','prosemirror-model','prosemirror-schema-list','prosemirror-state','prosemirror-transform','prosemirror-view','rope-sequence','w3c-keyname'];
const licenses = [];
for (const name of packages) {
  const pkg = JSON.parse(await readFile(new URL(`node_modules/${name}/package.json`, root), 'utf8'));
  const license = await readFile(new URL(`node_modules/${name}/LICENSE`, root), 'utf8');
  licenses.push(`${name}@${pkg.version}\n${license.replace(/\r\n?/g, '\n').trim()}\n`);
}
const outputs = [
  ['public/pages/vendor/editor.js', result.outputFiles[0].text],
  ['public/pages/vendor/LICENSES.txt', licenses.join('\n----------------------------------------\n\n')],
];
for (const [filename, contents] of outputs) await output(filename, contents);
console.log(process.argv.includes('--check') ? 'Pages appearance, bundle and notices: current (no writes)' : 'Pages appearance, bundle and notices generated');
