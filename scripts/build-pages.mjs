import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const result = await build({ absWorkingDir: fileURLToPath(root), entryPoints: ['public/pages/editor-source.js'],
  bundle: true, format: 'esm', platform: 'browser', target: ['es2020'], minify: true, legalComments: 'inline', write: false,
  banner: { js: '/* Generated by npm run build:pages. Pinned sources and MIT notices: ./vendor/LICENSES.txt */' } });
const packages = ['sortablejs','orderedmap','prosemirror-commands','prosemirror-history','prosemirror-keymap','prosemirror-model','prosemirror-schema-list','prosemirror-state','prosemirror-transform','prosemirror-view','rope-sequence','w3c-keyname'];
const licenses = [];
for (const name of packages) {
  const pkg = JSON.parse(await readFile(new URL(`node_modules/${name}/package.json`, root), 'utf8'));
  const license = await readFile(new URL(`node_modules/${name}/LICENSE`, root), 'utf8');
  licenses.push(`${name}@${pkg.version}\n${license.replace(/\r\n?/g, '\n').trim()}\n`);
}
const outputs = [
  ['public/pages/vendor/editor.js', result.outputFiles[0].text],
  ['public/pages/vendor/LICENSES.txt', licenses.join('\n----------------------------------------\n\n')],
];
for (const [filename, contents] of outputs) {
  const url = new URL(filename, root);
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8').catch(() => '') !== contents) throw new Error(`${filename} is stale; run npm run build:pages`);
  } else await writeFile(url, contents);
}
console.log(process.argv.includes('--check') ? 'Pages bundle and notices: current (no writes)' : 'Pages bundle and notices generated');
